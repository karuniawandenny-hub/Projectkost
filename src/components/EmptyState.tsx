import Link from "next/link";
import type { ReactNode } from "react";

type Props = {
  icon?: ReactNode;
  title: string;
  description?: string;
  action?: {
    label: string;
    href: string;
  };
};

/**
 * Empty state untuk daftar yang kosong. Sebelumnya banyak halaman cuma
 * tampil "Tidak ada data" plain text - tidak engaging dan tidak ada
 * call-to-action.
 */
export function EmptyState({ icon, title, description, action }: Props) {
  return (
    <div className="flex flex-col items-center justify-center rounded-xl border border-dashed border-slate-300 bg-slate-50/50 px-6 py-10 text-center">
      <div className="mb-3 grid h-14 w-14 place-items-center rounded-full bg-white text-slate-400 shadow-sm">
        {icon ?? <DefaultIcon />}
      </div>
      <h3 className="text-sm font-semibold text-slate-800">{title}</h3>
      {description && (
        <p className="mt-1 max-w-sm text-xs text-slate-500">{description}</p>
      )}
      {action && (
        <Link
          href={action.href}
          className="mt-4 inline-flex items-center gap-1 rounded-md bg-brand-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-brand-700"
        >
          {action.label}
        </Link>
      )}
    </div>
  );
}

